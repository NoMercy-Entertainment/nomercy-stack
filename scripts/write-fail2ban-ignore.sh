#!/bin/bash
# infra/nomercy-stack/scripts/write-fail2ban-ignore.sh
#
# Writes fail2ban's ignoreip list (gitignored: this repo is public). Called by
# provision-security.sh; reads ADMIN_IPS, TRUSTED_IPS, LOCAL_NETWORKS and
# SELF_ADDRESSES from the environment.
# TRUSTED_IPS (CI runner addresses) go only here: no UFW rule, no admin sites.
# A run with no TRUSTED_IPS keeps the trusted entries of the existing file.

set -euo pipefail

STACK_DIR="${STACK_DIR:-/opt/nomercy-stack}"
IGNORE_FILE="$STACK_DIR/fail2ban/config/fail2ban/jail.d/01-admin-ignoreip.local"

check_ips() {
    local name="$1" ip
    shift
    for ip in "$@"; do
        if ! [[ "$ip" =~ ^[0-9A-Fa-f:.]+(/[0-9]{1,3})?$ ]]; then
            echo "ERROR: '$ip' in $name is not an IP address or CIDR range" >&2
            exit 1
        fi
    done
}

admin_ips="$(echo "${ADMIN_IPS:-}" | tr ',' ' ' | xargs)"
trusted_ips="$(echo "${TRUSTED_IPS:-}" | tr ',' ' ' | xargs)"
# shellcheck disable=SC2086
check_ips ADMIN_IPS $admin_ips
# shellcheck disable=SC2086
check_ips TRUSTED_IPS $trusted_ips

if [ -z "$trusted_ips" ] && [ -f "$IGNORE_FILE" ]; then
    trusted_ips="$(sed -n 's/^# trusted-ips: //p' "$IGNORE_FILE" | head -1 | xargs)"
    # shellcheck disable=SC2086
    check_ips "trusted-ips in $IGNORE_FILE" $trusted_ips
fi

mkdir -p "$(dirname "$IGNORE_FILE")"
cat > "$IGNORE_FILE.tmp" <<EOF
# Generated by scripts/write-fail2ban-ignore.sh from the deploy's ADMIN_IPS and TRUSTED_IPS.
# Gitignored because the repo is public. Do not edit by hand.
# trusted-ips: $trusted_ips
[DEFAULT]
ignoreip = 127.0.0.1/8 ::1 ${LOCAL_NETWORKS:-} ${SELF_ADDRESSES:-} $admin_ips $trusted_ips
EOF
mv "$IGNORE_FILE.tmp" "$IGNORE_FILE"
